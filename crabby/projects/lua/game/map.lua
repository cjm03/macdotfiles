function map.draw()
    for row = 1, map.height do
        for col = 1, map.width do
            local tile = map.tiles[row][col]
            local quad = map.tileImages[tile]
            if quad then
                love.graphics.draw(
                    map.tilesetImage,
                    quad,
                    (col - 1) * map.tileSize,
                    (row - 1) * map.tileSize
                )
            end
        end
    end
end

function map.isBlocked(x, y)
    local col = math.floor(x / map.tileSize) + 1
    local row = math.floor(y / map.tileSize) + 1
    return map.tiles[row] and map.tiles[row][col] == 1
end

